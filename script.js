/* PORTFOLIO SLIDER */




(function(){
  const slider = document.getElementById('portfolioSlider');
  const dotsWrap = document.getElementById('sliderDots');
  if(!slider) return;

  const cards = slider.querySelectorAll('.portfolio-card');
  const cardWidth = () => cards[0].offsetWidth + 20; // 20 = gap
  let current = 0;

  // Создаём точки
  cards.forEach((_, i) => {
    const dot = document.createElement('button');
    dot.className = 'slider-dot' + (i === 0 ? ' active' : '');
    dot.addEventListener('click', () => goTo(i));
    dotsWrap.appendChild(dot);
  });

  function updateDots(){
    dotsWrap.querySelectorAll('.slider-dot').forEach((d, i) => {
      d.classList.toggle('active', i === current);
    });
  }

  function goTo(index){
    current = Math.max(0, Math.min(index, cards.length - 1));
    slider.scrollTo({ left: cardWidth() * current, behavior: 'smooth' });
    updateDots();
  }

  document.getElementById('slidePrev').addEventListener('click', () => goTo(current - 1));
  document.getElementById('slideNext').addEventListener('click', () => goTo(current + 1));

  // Синхронизация точек при ручном скролле
  slider.addEventListener('scroll', () => {
    const idx = Math.round(slider.scrollLeft / cardWidth());
    if(idx !== current){ current = idx; updateDots(); }
  }, { passive: true });
})();